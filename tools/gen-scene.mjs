// Generates hooks/scene.ts for the matrix-rain mod:
//   node tools/gen-scene.mjs hooks/scene.ts
//
// Both scenes are still: a fixed grid of characters, with nothing animated.
// The desktop app held every animated version still sooner or later (a scene
// that is costly to repaint is frozen, and repainting got costly whenever the
// app was busy drawing a reply). The rain itself now runs on the GPU, in
// hooks/rain.ts, which re-weighs this grid's pixels; its layout constants must
// match the ones here.
//
// RAIN_GRID: glyphs at BASE strength, what the shader plays over, and what
//   shows alone where no shader plays (mobile, Reduce Motion).
// RAIN_REST: the faint grid shown while Claude waits.
import { writeFileSync } from 'node:fs'

const out = process.argv[2]
let seed = 20261123
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296)
const pick = s => s[Math.floor(rnd() * s.length)]

const CHARS = 'ｱｲｳｴｵｶｷｸｹｺｻｼｽｾｿﾀﾁﾂﾃﾄﾅﾆﾇﾈﾉﾊﾋﾌﾍﾎﾏﾐﾑﾒﾓﾔﾕﾖﾗﾘﾙﾚﾛﾜﾝ0123457890123457Z:.=*+-|'
const W = 1600, H = 1000, FS = 18, COL = 20
const cols = Math.floor(W / COL)
const ROWS = Math.ceil(H / FS) + 1
const BASE = 0.2
const REST = 0.06

const columns = []
for (let i = 0; i < cols; i++) {
  const xs = [], ys = []
  let chars = ''
  for (let k = 0; k < ROWS; k++) { xs.push(0); ys.push(k * FS + FS - 3); chars += pick(CHARS) }
  // Glyphs sit from x+3 to about x+13 of their column; the shader reads the
  // background from the empty strip at x+17.
  columns.push(`<text transform="translate(${i * COL + 3} 0)" x="${xs.join(' ')}" y="${ys.join(' ')}">${chars}</text>`)
}

const svg = strength =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice"><style>
text{font-family:monospace;font-size:16px}
.bg{fill:#f6faf6}
.c{fill:#137a3a;fill-opacity:${strength}}
@media (prefers-color-scheme: dark){.bg{fill:#070b08}.c{fill:#5ef08a}}
</style><rect class="bg" x="0" y="0" width="${W}" height="${H}"/><g class="c">${columns.join('')}</g></svg>`

const grid = svg(BASE), rest = svg(REST)
for (const s of [grid, rest]) {
  if (s.length > 131072) throw new Error(`scene too long: ${s.length}`)
}
writeFileSync(out, `// Generated by tools/gen-scene.mjs: the still grid the rain plays over.\nexport const RAIN_GRID = ${JSON.stringify(grid)}\nexport const RAIN_REST = ${JSON.stringify(rest)}\n`)
console.log('columns', cols, 'rows', ROWS, 'grid chars', grid.length, 'rest chars', rest.length)
